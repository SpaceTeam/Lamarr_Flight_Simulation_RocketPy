def create_flight(constants, variations):
    """
    Create scenario flights for every configured environment.

    - Full-flight mode: 
        each scenario (nominal / no_main / ballistic) is simulated from launch to impact.
    - Scan mode (active for VARIATION_KEYS_WITHOUT_FLIGHT_PLOTS and deployable payloads): 
        for each launch configuration, simulates the ascent once and reuses its
        apogee state as the starting point for the descent scenarios, skipping ascent
        re-simulation across the scenario set.
    """
    print("Creating flights...")

    environments = lookup("environments", constants, variations)[0]
    has_drogue = any(key.startswith("parachutes_drogue_") for key in list(constants) + list(variations))
    has_payload = deployable_payload.has_deployable_payload(constants, variations)
    reuse_ascent_flights = any(key in variations for key in VARIATION_KEYS_WITHOUT_FLIGHT_PLOTS) or has_payload

    parameter_flights = []
    
    # defaults = {"flight_terminate_on_apogee": True}
    # add_defaults(parameter_flights, defaults, constants, variations)
    fill_parameters(parameter_flights, "flight_", constants, variations)
    fill_parameters_exact(parameter_flights, "rocket", constants, variations)

    if has_payload:
        fill_parameters_exact(parameter_flights, "payload_mass_total", constants, variations)

    check_required(parameter_flights, ["rail_length", "inclination", "heading"], "flight")

    # One bucket per environment; populated below as combinations are generated.
    flights_by_env = {env_name: [] for env_name in environments}
    ascent_flights_by_env = {env_name: [] for env_name in environments}
    scenarios_per_combo = 3 if has_drogue else 2
    flights_per_combo = scenarios_per_combo + 1 if reuse_ascent_flights else scenarios_per_combo
    total = count_combinations(parameter_flights, variations)
    step = max(1, total // 10)
    # Each combination produces one scenario set per environment, plus an ascent in reuse mode.
    print(f"Amount: {total * flights_per_combo * len(environments)}")

    # create one flight per scenario per environment; reuse ascent flight when configured
    for i, flight_values in enumerate(generate_combinations(parameter_flights, constants, variations), start=1):
        # Build the scenario-specific rocket copies once per combination, then reuse them across envs.
        payload_mass_total = flight_values.get("payload_mass_total", 0)
        scenario_rockets = build_scenario_rockets(flight_values["rocket"], has_drogue, payload_mass_total)
        meta = {key: flight_values[key] for key in variations if key in flight_values}

        print(f"{i / total:.0%}")
        # if i % step == 0 or i == total:
        #     print(f"{i / total:.0%}")
        
        for env_name, environment in environments.items():
            # if i / total >= 0.77:
            #     print(f"env={env_name}, flight_values={flight_values}")
            ascent_flight = None
            scenario_set = {}

            if reuse_ascent_flights:
                # First simulate the full-mass rocket only up to apogee
                ascent_flight = Flight(
                    rocket=flight_values["rocket"],
                    environment=environment,
                    rail_length=flight_values["flight_rail_length"],
                    inclination=flight_values["flight_inclination"],
                    heading=flight_values["flight_heading"],
                    terminate_on_apogee=True,
                    name=f"{env_name}_ascent",
                )
                attach_meta(ascent_flight, meta)
                ascent_flights_by_env[env_name].append(ascent_flight)

            # In reanalysis mode: we only compare to the nominal flight and optionally to a copy of it (matched flight)
            scenarios_for_env = (
                {"nominal": scenario_rockets["nominal"]}
                if env_name.startswith("Reanalysis")
                else scenario_rockets
            )

            for scenario_name, rocket in scenarios_for_env.items():
                # print(f"scenario_rockets={scenario_rockets}")
                flight_options = {
                    "rocket": rocket,
                    "environment": environment,
                    "rail_length": flight_values["flight_rail_length"],
                    "inclination": flight_values["flight_inclination"],
                    "heading": flight_values["flight_heading"],
                    "terminate_on_apogee": False,
                    "name": f"{env_name}_{scenario_name}",
                }

                if ascent_flight is not None:
                    # Continue the scenario from the ascent apogee; payload mass is removed when configured.
                    flight_options["initial_solution"] = ascent_flight

                flight = Flight(**flight_options)
                attach_meta(flight, meta)
                scenario_set[scenario_name] = flight

            flights_by_env[env_name].append(scenario_set)

    constants, variations = register("flights_by_env", flights_by_env, constants, variations)

    if reuse_ascent_flights:
        constants, variations = register("ascent_flights_by_env", ascent_flights_by_env, constants, variations)

    if has_payload:
        constants, variations = deployable_payload.create_payload(constants, variations)
        constants, variations = deployable_payload.create_payload_flight(constants, variations)

    return constants, variations


def build_scenario_rockets(base_rocket, has_drogue, payload_mass_total=0):
    """
    Build the rocket variants for the descent scenarios by deep-copying the base rocket and
    trimming its parachute list. Returns a dict of scenario_name -> rocket.

    When a deployable payload is configured, the scenario rockets represent the post-separation
    rocket, so the configured payload mass is removed before descent is simulated.
    """
    # Each scenario gets its own deep copy so RocketPy can hold scenario-specific parachute lists.
    nominal_rocket = copy.deepcopy(base_rocket)
    ballistic_rocket = copy.deepcopy(base_rocket)
    ballistic_rocket.parachutes = []

    if not has_drogue:
        scenario_rockets = {"nominal": nominal_rocket, "ballistic": ballistic_rocket}
    else:
        no_main_rocket = copy.deepcopy(base_rocket)
        no_main_rocket.parachutes = [parachute for parachute in no_main_rocket.parachutes if parachute.name != "main"]
        scenario_rockets = {"nominal": nominal_rocket, "no_main": no_main_rocket, "ballistic": ballistic_rocket}

    payload_mass_kg = grams_to_kilograms(payload_mass_total)

    if payload_mass_kg > 0:
        for rocket in scenario_rockets.values():
            # remove payload mass from rocket after separation
            rocket.mass -= payload_mass_kg

            if rocket.mass <= 0:
                raise ValueError("payload_mass_total must be smaller than the rocket mass.")

    return scenario_rockets