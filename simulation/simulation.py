def get_parachute_cd_s(parachute_values, prefix):
    """
    Return `cd_s` directly or compute it from drag coefficient and area inputs.
    """
    cd_s_key = f"{prefix}_cd_s"
    cd_key = f"{prefix}_cd"
    radius_key = f"{prefix}_radius"
    fabric_area_key = f"{prefix}_fabric_area"

    if cd_s_key in parachute_values:
        return parachute_values[cd_s_key]

    if cd_key in parachute_values and fabric_area_key in parachute_values:
        return parachute_values[cd_key] * parachute_values[fabric_area_key]

    if cd_key in parachute_values and radius_key in parachute_values:
        return parachute_values[cd_key] * pi * parachute_values[radius_key] ** 2

    raise ValueError(f"Parachute '{prefix}' needs either cd_s, cd + radius, or cd + fabric_area.")


