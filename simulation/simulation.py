def create_rocket(constants, variations, OUTPUT_LEVEL):
    """
    Create RocketPy rocket objects.

    The config uses explicit ``*_from_tip`` values for measured positions. They are converted to
    RocketPy's bottom-origin coordinate system inside this function.
    """
    print("Creating rocket...")

    constants, variations = create_nosecone(constants, variations)
    constants, variations = create_tailcone(constants, variations)
    constants, variations = create_fins(constants, variations, OUTPUT_LEVEL)
    constants, variations = create_parachutes(constants, variations, OUTPUT_LEVEL)

    parameter_rockets = []

    # defaults = {
    #     "nozzle_position": 0,
    #     "rocket_moment_of_intertia_XY": 0.1,
    #     "rocket_moment_of_intertia_Z": 1,
    # }
    # add_defaults(parameter_rockets, defaults, constants, variations)
    fill_parameters(parameter_rockets, "rocket_", constants, variations)
    fill_parameters(parameter_rockets, "railbuttons_", constants, variations)
    fill_parameters_exact(
        parameter_rockets,
        [
            "motor",
            "nosecone",
            "tailcone",
            "fin_set",
            "parachutes",
            "fins_position",
            "tailcone_length",
            "tailcone_cylindrical_section_length",
        ],
        constants,
        variations,
    )

    check_required(
        parameter_rockets,
        [
            "diameter",
            "length",
            "total_mass_without_motor",
            "total_CG_without_motor_from_tip",
            "moment_of_intertia_XY",
            "moment_of_intertia_Z",
            "power_off_drag",
            "power_on_drag",
        ],
        "rocket",
    )
    check_required(parameter_rockets, ["upper_from_tip", "lower_from_tip"], "railbuttons")
    check_required(parameter_rockets, ["motor", "nosecone", "tailcone", "fin_set", "parachutes"])
    check_required(parameter_rockets, ["position"], "fins")
    check_required(parameter_rockets, ["length", "cylindrical_section_length"], "tailcone")

    rockets = []

    for rocket_values in generate_combinations(parameter_rockets, constants, variations):
        rocket_length_m = millimeters_to_meters(rocket_values["rocket_length"])
        center_of_mass_from_bottom = get_position_from_tip(
            rocket_values["rocket_total_CG_without_motor_from_tip"],
            rocket_length_m,
        )
        upper_railbutton_from_bottom = get_position_from_tip(
            rocket_values["railbuttons_upper_from_tip"],
            rocket_length_m,
        )
        lower_railbutton_from_bottom = get_position_from_tip(
            rocket_values["railbuttons_lower_from_tip"],
            rocket_length_m,
        )
        fin_position_from_bottom = millimeters_to_meters(rocket_values["fins_position"])
        tail_position_from_bottom = millimeters_to_meters(
            rocket_values["tailcone_length"] - rocket_values["tailcone_cylindrical_section_length"]
        )

        rocket = Rocket(
            radius=millimeters_to_meters(rocket_values["rocket_diameter"]) / 2,                      # m
            mass=grams_to_kilograms(rocket_values["rocket_total_mass_without_motor"]),               # kg
            inertia=(
                rocket_values["rocket_moment_of_intertia_XY"],
                rocket_values["rocket_moment_of_intertia_XY"],
                rocket_values["rocket_moment_of_intertia_Z"],
            ),
            power_off_drag=get_project_file(constants, rocket_values["rocket_power_off_drag"]),
            power_on_drag=get_project_file(constants, rocket_values["rocket_power_on_drag"]),
            center_of_mass_without_motor=center_of_mass_from_bottom,                                # m
            coordinate_system_orientation="tail_to_nose",
        )
        rocket.add_motor(rocket_values["motor"], position=0)
        rocket.set_rail_buttons(
            upper_button_position=upper_railbutton_from_bottom,
            lower_button_position=lower_railbutton_from_bottom,
        )
        rocket.add_surfaces(
            surfaces=[rocket_values["nosecone"], rocket_values["fin_set"], rocket_values["tailcone"]],
            positions=[rocket_length_m, fin_position_from_bottom, tail_position_from_bottom],
        )
        rocket.parachutes = list(rocket_values["parachutes"].values())

        attach_meta(rocket, {key: rocket_values[key] for key in variations if key in rocket_values})
        rockets.append(rocket)
        
        if OUTPUT_LEVEL > 1:
            print_one_rocket(rocket, rocket_length_m)
            plot_one_rocket(rocket)

    return register("rocket", rockets, constants, variations)

