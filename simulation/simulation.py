def create_engine(constants, variations, OUTPUT_LEVEL):
    """
    Create the configured motor type.
    """
    print("Creating engine...")

    parameter_engine = []
    fill_parameters(parameter_engine, "engine_", constants, variations)
    check_required(parameter_engine, {"type"}, "engine")

    engine_type = lookup("engine_type", constants, variations)[0]

    if engine_type == "liquid":
        return create_liquid_engine(constants, variations, OUTPUT_LEVEL)

    if engine_type == "solid":
        return create_solid_engine(constants, variations, OUTPUT_LEVEL)

    raise ValueError(f"Unknown engine_type '{engine_type}'. Use 'solid' or 'liquid'.")


def create_liquid_engine(constants, variations, OUTPUT_LEVEL):
    """
    Create liquid motors from tank and mass-flow configuration.
    """
    print("Creating liquid engine...")

    # TODO: use fuel instead of "ethanol"
    parameter_motor = []
    fill_parameters_exact(parameter_motor, ["holddown_time", "nozzle_diameter", "thrust"], constants, variations)
    fill_parameters(parameter_motor, "nitrogen_tank_", constants, variations)
    fill_parameters(parameter_motor, "ethanol_tank_", constants, variations)
    fill_parameters(parameter_motor, "lox_tank_", constants, variations)
    fill_parameters(parameter_motor, "pressure_", constants, variations)
    fill_parameters(parameter_motor, "temperature_", constants, variations)

    check_required(parameter_motor, ["holddown_time", "nozzle_diameter", "thrust"])
    check_required(parameter_motor, ["length", "outer_diameter", "volume", "massflow"], "nitrogen_tank")
    check_required(parameter_motor, ["length", "outer_diameter", "volume", "massflow"], "ethanol_tank")
    check_required(parameter_motor, ["length", "outer_diameter", "volume", "massflow"], "lox_tank")
    check_required(parameter_motor, ["nitrogen_tank_CG_ethanol", "nitrogen_tank_CG_lox"])
    check_required(parameter_motor, ["temperature_nitrogen", "temperature_ethanol", "temperature_lox"])
    check_required(parameter_motor, ["pressure_nitrogen", "pressure_ethanol", "pressure_lox"])
    
    # defaults = {
    #     "temperature_nitrogen": 298.15,                # K       # preset (= 25°C)
    #     "temperature_ethanol": 298.15,                # K       # preset (= 25°C)
    #     "temperature_lox": 93.15,                    # K       # preset (= -180°C)
    #     "pressure_nitrogen": 30000000,              # Pa     # preset
    #     "pressure_ethanol": 3000000,              # Pa     # preset
    #     "pressure_lox": 3000000,             # Pa     # preset
    # }
    # add_defaults(parameter_motor, defaults, constants, variations)
    
    if DEBUG: 
        print(parameter_motor)
        
    motors = []

    # TODO: use "pressure_gas" instead of nitrogen
    for motor_values in generate_combinations(parameter_motor, constants, variations):
        # Propellants

        # define density
        rho_nitrogen = CP.PropsSI("D", "T", motor_values["temperature_nitrogen"], "P|gas", motor_values["pressure_nitrogen"], "N2")        # kg/m^3
        rho_ethanol = CP.PropsSI("D", "T|liquid", motor_values["temperature_ethanol"], "P", motor_values["pressure_ethanol"], "ethanol")   # kg/m^3
        rho_lox = CP.PropsSI("D", "T|liquid", motor_values["temperature_lox"], "P", motor_values["pressure_lox"], "oxygen")                # kg/m^3

        # define fluids
        nitrogen = Fluid(name="N2", density=rho_nitrogen)
        ethanol = Fluid(name="ethanol", density=rho_ethanol)
        lox = Fluid(name="LOX", density=rho_lox)

        # define tanks geometry
        nitrogen_tank_shape = CylindricalTank(
            radius=millimeters_to_meters(motor_values["nitrogen_tank_outer_diameter"]) / 2,
            height=millimeters_to_meters(motor_values["nitrogen_tank_length"]),
            spherical_caps=True,
        )
        ethanol_tank_shape = CylindricalTank(
            radius=millimeters_to_meters(motor_values["ethanol_tank_outer_diameter"]) / 2,
            height=millimeters_to_meters(motor_values["ethanol_tank_length"]),
            spherical_caps=True,
        )
        lox_tank_shape = CylindricalTank(
            radius=millimeters_to_meters(motor_values["lox_tank_outer_diameter"]) / 2,
            height=millimeters_to_meters(motor_values["lox_tank_length"]),
            spherical_caps=True,
        )

        mass_nitrogen = motor_values["nitrogen_tank_volume"] / 1000 * rho_nitrogen          # m
        mass_ethanol = motor_values["ethanol_tank_volume"] / 1000 * rho_ethanol             # m
        mass_lox = motor_values["lox_tank_volume"] / 1000 * rho_lox                         # m

        burn_time_ethanol = mass_ethanol / motor_values["ethanol_tank_massflow"]            # s
        burn_time_lox = mass_lox / motor_values["lox_tank_massflow"]
        # account for holddown
        burn_time = min(burn_time_ethanol, burn_time_lox) - motor_values["holddown_time"]

        mass_nitrogen = motor_values["nitrogen_tank_massflow"] * burn_time + 0.0001
        mass_ethanol = motor_values["ethanol_tank_massflow"] * burn_time + 0.0001
        mass_lox = motor_values["lox_tank_massflow"] * burn_time + 0.0001

        # define tanks
        nitrogen_tank = MassFlowRateBasedTank(
            name="nitrogen tank",
            geometry=nitrogen_tank_shape,
            flux_time=burn_time,                              # s
            initial_liquid_mass=0,                            # kg
            initial_gas_mass=mass_nitrogen,                   # kg
            liquid_mass_flow_rate_in=0,                       # kg/s
            liquid_mass_flow_rate_out=0,                      # kg/s
            gas_mass_flow_rate_in=0,                          # kg/s
            gas_mass_flow_rate_out=lambda t: motor_values["nitrogen_tank_massflow"],   # ks/s
            liquid=Fluid(name="liquid", density=0.0001),  # ignore
            gas=nitrogen,
        )
        ethanol_tank = MassFlowRateBasedTank(
            name="fuel tank",
            geometry=ethanol_tank_shape,
            flux_time=burn_time,                                 # s
            initial_liquid_mass=mass_ethanol,                    # kg
            initial_gas_mass=0,                                 # kg
            liquid_mass_flow_rate_in=0,                         # kg/s
            liquid_mass_flow_rate_out=lambda t: motor_values["ethanol_tank_massflow"], # kg/s
            gas_mass_flow_rate_in=lambda t: motor_values["nitrogen_tank_massflow"],    # kg/s
            gas_mass_flow_rate_out=0,                         # kg/s
            liquid=ethanol,
            gas=nitrogen,
        )
        lox_tank = MassFlowRateBasedTank(
            name="oxidizer tank",
            geometry=lox_tank_shape,
            flux_time=burn_time,                                    # s
            initial_liquid_mass=mass_lox,                           # kg
            initial_gas_mass=0,                                     # kg
            liquid_mass_flow_rate_in=0,                             # kg/s
            liquid_mass_flow_rate_out=lambda t: motor_values["lox_tank_massflow"],      # kg/s
            gas_mass_flow_rate_in=lambda t: motor_values["nitrogen_tank_massflow"],     # kg/s
            gas_mass_flow_rate_out=0,                               # kg/s
            liquid=lox,
            gas=nitrogen,
        )

        if DEBUG: 
            print(motor_values["thrust"])
            
        motor = LiquidMotor(
            dry_mass=0.0001,                        # kg
            dry_inertia=(0, 0, 0),                  # kg*m^2
            center_of_dry_mass_position=0,          # m
            nozzle_radius=millimeters_to_meters(motor_values["nozzle_diameter"]) / 2, # m
            nozzle_position=0,  # m
            thrust_source=get_project_file(constants, motor_values["thrust"]),   # N
            burn_time=burn_time,                 # s
            coordinate_system_orientation="nozzle_to_combustion_chamber",
        )
        motor.add_tank(tank=nitrogen_tank, position=millimeters_to_meters(motor_values["nitrogen_tank_CG_ethanol"]))
        motor.add_tank(tank=nitrogen_tank, position=millimeters_to_meters(motor_values["nitrogen_tank_CG_lox"]))
        motor.add_tank(tank=ethanol_tank, position=millimeters_to_meters(motor_values["ethanol_tank_CG"]))
        motor.add_tank(tank=lox_tank, position=millimeters_to_meters(motor_values["lox_tank_CG"]))

        attach_meta(motor, {key: motor_values[key] for key in variations if key in motor_values})
        motors.append(motor)
        
        if OUTPUT_LEVEL > 1:
            print_one_motor(motor, type="liquid")
            plot_one_motor(motor)
        
    return register("motor", motors, constants, variations)


def create_solid_engine(constants, variations, OUTPUT_LEVEL):
    """
    Create solid motors from the config.
    """
    print("Creating solid engine...")

    parameter_motor = []
    fill_parameters(parameter_motor, "motor_", constants, variations)
    # defaults = {
    #     "motor_coordinate_system_orientation": "nozzle_to_combustion_chamber",
    #     "motor_dry_inertia": (0.1, 0.1, 0.001),
    #     "holddown_time": 0,
    # }
    # add_defaults(parameter_motor, defaults, constants, variations)
    check_required(
        parameter_motor,
        [
            "name",
            "total_mass",
            "propellant_mass",
            "diameter",
            "length",
            "burn_time",
            "center_of_dry_mass_factor",
            "thrust",
        ],
        "motor",
    )
    
    if DEBUG: 
        print(parameter_motor)

    motors = []

    for motor_values in generate_combinations(parameter_motor, constants, variations):
        motor_total_mass = grams_to_kilograms(motor_values["motor_total_mass"])
        motor_propellant_mass = grams_to_kilograms(motor_values["motor_propellant_mass"])
        motor_dry_mass = motor_total_mass - motor_propellant_mass
        motor_radius = millimeters_to_meters(motor_values["motor_diameter"]) / 2
        motor_length = millimeters_to_meters(motor_values["motor_length"])
        motor_volume = pi * motor_radius**2 * motor_length                                                  # m³
        motor_grain_density = motor_propellant_mass / motor_volume                                          # kg/m³
        
        # inertia of motor without propellant (dry mass) using formula for thin cylindrical shell with open ends
        dry_inertia_x_y = 1 / 12 * motor_dry_mass * (6 * motor_radius**2 + motor_length**2)                 # kg*m²
        dry_inertia_z = motor_dry_mass * motor_radius**2                                                    # kg*m²

        motor = SolidMotor(
            thrust_source=get_project_file(constants, motor_values["motor_thrust"]),
            dry_mass=motor_dry_mass,
            dry_inertia=(dry_inertia_x_y, dry_inertia_x_y, dry_inertia_z),                                  # kg*m²
            nozzle_radius=motor_radius,
            grain_number=1,
            grain_density=motor_grain_density,
            grain_outer_radius=motor_radius,
            grain_initial_inner_radius=0,
            grain_initial_height=motor_length,
            grain_separation=0,
            grains_center_of_mass_position=motor_length / 2,
            center_of_dry_mass_position=motor_length * motor_values["motor_center_of_dry_mass_factor"],
            nozzle_position=0,
            burn_time=motor_values["motor_burn_time"],
            throat_radius=motor_radius / 2,
            coordinate_system_orientation="nozzle_to_combustion_chamber",
        )

        attach_meta(motor, {key: motor_values[key] for key in variations if key in motor_values})
        motors.append(motor)

        if OUTPUT_LEVEL > 1:
            print_one_motor(motor, type="solid", inertia=(dry_inertia_x_y, dry_inertia_z))
            plot_one_motor(motor)
        
    return register("motor", motors, constants, variations)


