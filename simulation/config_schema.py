class EnvironmentConfig(_Base):
    """Launch site environment and atmosphere model configuration.

    Attributes:
        date: 
            Magic string 'tomorrow_08_local' for tomorrow 8 AM, or an explicit local-time
            [year, month, day, hour, min, sec] list.
        latitude: 
            Launch site latitude [°].
        longitude: 
            Launch site longitude [°].
        max_expected_height: 
            Maximum expected height above ground level [m].
        elevation: 
            Launch site elevation above sea level [m].
        timezone: 
            Local launch-site timezone string (e.g. 'Europe/Berlin').
        envType: 
            Atmosphere model type.
            A list requests multiple environments. Do not mix reanalysis types with others.<br>
            Supported values:
            - `standard_atmosphere`: RocketPy standard atmosphere.
            - `Windy`: RocketPy Windy forecast.
            - `custom_atmosphere`: atmosphere loaded from CSV files generated by the weather export script.
            - `reanalysis`: RocketPy reanalysis file.
            - `reanalysis_custom`: custom_atmosphere loaded from existing historical CSV files.
        reanalysis_csv: 
            CSV filenames keyed by model name, used with 'reanalysis_custom'.
        windy_weather_models: 
            Windy weather model name(s), used with 'Windy'.
        custom_weather_models: 
            Custom weather model name(s), used with 'custom_atmosphere'.
        reanalysis_file: 
            Reanalysis data file, used with 'reanalysis'.
        reanalysis_dictionary: 
            Reanalysis dictionary, used with 'reanalysis'.
    """
    date: Union[str, list[int]]
    latitude: _VNum
    longitude: _VNum
    max_expected_height: _VNum
    elevation: _VNum
    timezone: str
    envType: Union[str, list[str]]
    reanalysis_csv: Optional[dict[str, str]] = None
    windy_weather_models: Optional[Union[str, list[str]]] = None
    custom_weather_models: Optional[Union[str, list[str]]] = None
    reanalysis_file: Optional[str] = None
    reanalysis_dictionary: Optional[Any] = None


