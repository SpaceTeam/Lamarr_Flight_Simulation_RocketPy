class FinsConfig(_Base):
    """Fin set geometry. Supports freeform (shape_points) or trapezoidal fins.

    Attributes:
        amount: 
            Number of fins.
        position: 
            Distance from the fin root trailing edge to the rocket rear end [mm].
        name: 
            Fin set name / type string.
        shape_points: 
            Freeform fin outline as [(x, y)] points in meters. [0, 0] is
            the root leading edge. The polygon is closed automatically.
        root_chord: 
            Root chord length for trapezoidal fins [mm].
        tip_chord: 
            Tip chord length for trapezoidal fins [mm].
        span: 
            Fin span for trapezoidal fins [mm].
        sweep_length: 
            Sweep length for trapezoidal fins [mm].
    """
    amount: _VInt
    position: _VNum
    name: str
    shape_points: Optional[list[list[float]]] = None
    root_chord: Optional[_VNum] = None
    tip_chord: Optional[_VNum] = None
    span: Optional[_VNum] = None
    sweep_length: Optional[_VNum] = None


