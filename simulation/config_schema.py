"""
Pydantic models for config.json.

Each section of the JSON maps to a model class. Use `Config.model_validate(data)`
to parse and validate a loaded JSON dict. Keys starting with `_` (comments / disabled
entries) are silently ignored by every model via `extra="ignore"`.

Any numeric field accepts a single value or a list for parameter sweeps. Range strings
("start..stop:step") are expanded to lists by load_config before validation reaches here.
"""

from __future__ import annotations
from pathlib import Path
from typing import Union, Optional, Any, Literal
from pydantic import BaseModel, ConfigDict, Field

# Sweepable numeric types. Any field typed with these accepts a single value or a list.
_VNum = Union[float, list[float]]
_VInt = Union[int, list[int]]


def strip_comments(data):
    """Recursively remove keys starting with '_' (comments / disabled entries) from dicts."""
    if isinstance(data, dict):
        return {k: strip_comments(v) for k, v in data.items() if not k.startswith("_")}
    if isinstance(data, list):
        return [strip_comments(item) for item in data]
    return data


class _Base(BaseModel):
    """Base: silently drops unknown keys not defined in the schema."""
    model_config = ConfigDict(extra="ignore")


