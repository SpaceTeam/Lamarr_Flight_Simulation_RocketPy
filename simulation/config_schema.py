class ParachuteConfig(_Base):
    """Single parachute deployment and drag configuration.

    Attributes:
        trigger: 
            Deployment trigger: altitude AGL [m] as a float, or the string 'apogee'.
        sampling_rate: 
            Parachute sensor sampling rate [Hz].
        cd_s: 
            Drag area (cd × projected area) [m²]. Provide this or cd + (radius or
            fabric_area).
        cd: 
            Drag coefficient. Combine with radius or fabric_area to derive cd_s.
        radius: 
            Projected parachute radius [m]. Used with cd to compute cd_s.
        fabric_area: 
            Parachute fabric area [m²]. Used with cd to compute cd_s when
            projected area is close to fabric area.
        lag: 
            Deployment lag after trigger [s].
        noise: 
            Pressure sensor noise model as (mean [Pa], std_dev [Pa], time_correlation).
    """
    trigger: Union[_VNum, str]
    sampling_rate: _VNum
    cd_s: Optional[_VNum] = None
    cd: Optional[_VNum] = None
    radius: Optional[_VNum] = None
    fabric_area: Optional[_VNum] = None
    lag: Optional[_VNum] = None
    noise: Optional[tuple] = None


class ParachutesConfig(_Base):
    """All parachutes on the rocket.

    Attributes:
        main: 
            Main (recovery) parachute.
        drogue: 
            Drogue parachute deployed at apogee.
        payload: 
            Payload parachute for a separating payload.
    """
    main: ParachuteConfig
    drogue: Optional[ParachuteConfig] = None
    payload: Optional[ParachuteConfig] = None


