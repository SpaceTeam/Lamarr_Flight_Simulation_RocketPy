class Config(_Base):
    """Full project config loaded from config.json.
    
    Attributes:
        project (str): 
            Project name, used for labeling outputs. 
        output_level (int): Controls amount of output generated.
                - `output_level = 0`    (standard): most important prints + landing/safety plots
                - `output_level = 1`    (detailed): level 0 + per-flight custom plots + env prints
                - `output_level = 2`    (more detailed): level 1 + rocket/motor prints
                - `output_level = 3`    (debug): level 2 + more env plots
        environment (EnvironmentConfig): 
            Environment and atmosphere model configuration. Details see EnvironmentConfig.
        engine (EngineConfig): 
            Motor propulsion type selection (solid or liquid). Details see EngineConfig.
        motor (MotorConfig): 
            Solid motor configuration. Required when engine.type is 'solid'. Details see MotorConfig.
        liquid_engine (LiquidEngineConfig): 
            Liquid engine configuration. Required when engine.type is 'liquid'. Details see LiquidEngineConfig.
        rocket (RocketConfig): 
            Rocket body geometry, mass properties, and drag curves. Details see RocketConfig.
        nosecone (NoseconeConfig): 
            Nosecone geometry. Details see NoseconeConfig.
        railbuttons (RailbuttonsConfig): 
            Rail button positions. Details see RailbuttonsConfig.
        tailcone (TailconeConfig): 
            Tailcone geometry. Details see TailconeConfig.
        fins (FinsConfig): 
            Fin set geometry. Details see FinsConfig.
        parachutes (ParachutesConfig): 
            Parachute deployment and drag configuration. Details see ParachutesConfig.
        flight (FlightConfig): 
            Launch rail configuration and sweep parameters. Details see FlightConfig.
        payload (PayloadConfig): 
            Deployable payload configuration. Details see PayloadConfig.
        reanalysis (ReanalysisConfig): 
            Flight-computer data sources and matched-flight configuration for reanalysis mode. Details see ReanalysisConfig.
    """
    project: str
    output_level: int = 0
    environment: EnvironmentConfig
    engine: EngineConfig
    motor: Optional[MotorConfig] = None
    liquid_engine: Optional[LiquidEngineConfig] = None
    rocket: RocketConfig
    nosecone: NoseconeConfig
    railbuttons: RailbuttonsConfig
    tailcone: TailconeConfig
    fins: FinsConfig
    parachutes: ParachutesConfig
    flight: FlightConfig
    payload: PayloadConfig = PayloadConfig()
    reanalysis: Optional[ReanalysisConfig] = None


