class LiquidTankConfig(_Base):
    """Propellant (fuel or oxidizer) tank geometry, flow rate, and fluid properties.

    Attributes:
        length: 
            Tank length [mm].
        outer_diameter: 
            Tank outer diameter [mm].
        volume: 
            Propellant volume [L].
        massflow: 
            Propellant mass flow rate [kg/s].
        position: 
            Tank CG position from the nozzle [mm].
        substance: 
            CoolProp fluid name for this propellant (e.g. 'ethanol', 'oxygen').
        temperature: 
            Propellant temperature [K].
        pressure: 
            Tank pressure [Pa].
    """
    length: _VNum
    outer_diameter: _VNum
    volume: _VNum
    massflow: _VNum
    position: _VNum
    substance: str
    temperature: _VNum
    pressure: _VNum


