MatchParameter = Literal["heading", "inclination", "velocity"]


class MatchedFlightConfig(_Base):
    """A flight that branches off the nominal at match_time with a sensor-matched initial state.

    Attributes:
        match_time: 
            Time [s] at which to branch off the nominal flight and apply
            sensor-matched attitude/velocity.
        match_parameters: 
            Flight-computer parameters to match at match_time.
            Any subset of: 'heading', 'inclination', 'velocity'.
        motor: 
            Motor overrides applied to the matched flight.
        parachutes: 
            Per-parachute overrides keyed by parachute name (e.g. 'main', 'drogue').
    """
    match_time: Optional[_VNum] = None
    match_parameters: list[MatchParameter] = Field(default_factory=list)
    motor: Optional[MotorOverrideConfig] = None
    parachutes: Optional[dict[str, ParachuteOverrideConfig]] = None


class ReanalysisConfig(_Base):
    """Flight-computer data sources and matched-flight configuration.

    Attributes:
        sources: 
            Flight computers to load data from. Any subset of: 'cats_vega', 'altimax', 'rcu'.
        matched_flight: 
            Configuration for the sensor-matched flight branch. Omit to skip matched-flight simulation.
    """
    sources: list[str]
    matched_flight: Optional[MatchedFlightConfig] = None


